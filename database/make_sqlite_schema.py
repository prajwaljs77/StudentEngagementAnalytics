"""Derives tests/sqlite_schema.sql (used ONLY by pytest) from database/schema.sql."""
import re
from pathlib import Path

root = Path(__file__).resolve().parent
src = (root / "schema.sql").read_text()
src = "\n".join(l for l in src.split("\n") if not l.strip().startswith("--"))
src = src[src.index("CREATE TABLE users"):]
out = []
for stmt in src.split(";"):
    stmt = stmt.strip()
    if not stmt.startswith("CREATE TABLE"):
        continue
    stmt = stmt.replace(") ENGINE=InnoDB", ")")
    stmt = re.sub(r"(\w+)\s+INT UNSIGNED NOT NULL AUTO_INCREMENT", r"\1 INTEGER PRIMARY KEY AUTOINCREMENT", stmt)
    stmt = re.sub(r"\n\s*PRIMARY KEY \(\w+\),?", "", stmt)
    stmt = re.sub(r"\n\s*(?<!UNIQUE )KEY \w+ \([^)]*\),?", "", stmt)
    stmt = re.sub(r"UNIQUE KEY \w+ ", "UNIQUE ", stmt)
    stmt = re.sub(r"ENUM\([^)]*\)", "TEXT", stmt)
    stmt = stmt.replace("INT UNSIGNED", "INTEGER").replace("DECIMAL(5,2)", "REAL")
    stmt = re.sub(r"CONSTRAINT \w+ FOREIGN KEY", "FOREIGN KEY", stmt)
    stmt = re.sub(r"CONSTRAINT \w+ CHECK", "CHECK", stmt)
    stmt = re.sub(r",\s*\n\)", "\n)", stmt)
    out.append(stmt + ";")
(root.parent / "tests" / "sqlite_schema.sql").write_text(
    "-- Generated by database/make_sqlite_schema.py. Used ONLY by automated tests.\n" + "\n\n".join(out) + "\n")
