"""Generates database/seed.sql (+ sample import CSVs) with consistent synthetic demo data.
Run from the project folder:  python -m database.generate_seed
All timestamps in seed.sql are relative to NOW() (MySQL), so the data is always "recent".
Demo password for every seeded account: Demo@1234  (DEMO ONLY - change/remove outside local demos)."""
import csv
from datetime import datetime, timedelta
from pathlib import Path

import numpy as np
from werkzeug.security import generate_password_hash

from ml.simulation import simulate_pair

ROOT = Path(__file__).resolve().parent
REF = datetime(2025, 1, 1)
DEMO_PASSWORD = "Demo@1234"

FACULTY = [("Dr. Anita Rao", "faculty1@example.edu"), ("Prof. Rahul Mehta", "faculty2@example.edu")]
STUDENTS = ["Aarav Sharma", "Diya Patel", "Rohan Gupta", "Isha Nair", "Kabir Singh", "Meera Iyer", "Arjun Reddy", "Sneha Kulkarni",
            "Vikram Joshi", "Ananya Das", "Nikhil Verma", "Priya Menon", "Siddharth Rao", "Tanvi Shah", "Harsh Vardhan",
            "Pooja Bhat", "Manish Kumar", "Riya Chatterjee"]
COURSES = [("Data Structures", 1, "Semester 2"), ("Database Management Systems", 1, "Semester 2"),
           ("Machine Learning Fundamentals", 2, "Semester 3"), ("Web Technologies", 2, "Semester 3")]
INACTIVE = {3, 11}        # student indexes (0-based) forced inactive for the last 20 days
LOW_SCORE = {5, 13}       # students forced to low assessment scores


def ago(t):
    return max(0, int((REF - t).total_seconds() // 60))


def expr(minutes):
    return f"NOW() - INTERVAL {minutes} MINUTE"


def q(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    rng = np.random.default_rng(7)
    pw = generate_password_hash(DEMO_PASSWORD)
    out = ["-- Demo seed data (synthetic). Generated by database/generate_seed.py", "USE student_engagement_db;",
           "SET SQL_SAFE_UPDATES = 0;", "SET FOREIGN_KEY_CHECKS = 0;", "TRUNCATE TABLE alerts;",
           "TRUNCATE TABLE engagement_predictions;", "TRUNCATE TABLE assessments;", "TRUNCATE TABLE activities;",
           "TRUNCATE TABLE enrollments;", "TRUNCATE TABLE courses;", "TRUNCATE TABLE users;",
           "SET FOREIGN_KEY_CHECKS = 1;", ""]
    users = [(i + 1, n, e, "faculty") for i, (n, e) in enumerate(FACULTY)]
    users += [(len(FACULTY) + 1 + i, n, f"student{i + 1:02d}@example.edu", "student") for i, n in enumerate(STUDENTS)]
    out.append("INSERT INTO users (user_id, name, email, password_hash, role, created_at) VALUES")
    out.append(",\n".join(f"({u[0]}, {q(u[1])}, {q(u[2])}, {q(pw)}, {q(u[3])}, {expr(60 * 24 * 90)})" for u in users) + ";\n")
    out.append("INSERT INTO courses (course_id, course_name, faculty_id, semester, created_at) VALUES")
    out.append(",\n".join(f"({i + 1}, {q(n)}, {f}, {q(s)}, {expr(60 * 24 * 80)})" for i, (n, f, s) in enumerate(COURSES)) + ";\n")

    enroll, acts, asm = [], [], []
    for si in range(len(STUDENTS)):
        sid = len(FACULTY) + 1 + si
        for cid in sorted({si % 4 + 1, (si + 1 + si // 4) % 4 + 1}):
            enroll.append((len(enroll) + 1, cid, sid))
            a, s = simulate_pair(rng, REF)
            seen = set()
            for t, d, when in a:
                m = ago(when)
                if when >= REF or m > 60 * 24 * 42:
                    continue
                if si in INACTIVE and m < 60 * 24 * 20:
                    continue
                key = (t, m)
                if key in seen:
                    continue
                seen.add(key)
                acts.append((sid, cid, t, d, m))
            for r in s:
                score = min(r["score"], 35.0 + (r["score"] % 7)) if si in LOW_SCORE else r["score"]
                acts_m = ago(r["assessed_at"])
                due = expr(ago(r["due_at"])) if r["due_at"] else "NULL"
                sub = expr(ago(r["submitted_at"])) if r["submitted_at"] else "NULL"
                asm.append((sid, cid, round(score, 1), r["assessment_type"], r["title"], due, sub, expr(acts_m)))
    out.append("INSERT INTO enrollments (enrollment_id, course_id, student_id, enrolled_at) VALUES")
    out.append(",\n".join(f"({i}, {c}, {s}, {expr(60 * 24 * 70)})" for i, c, s in enroll) + ";\n")
    for i in range(0, len(acts), 250):
        out.append("INSERT INTO activities (student_id, course_id, activity_type, duration, activity_time, source) VALUES")
        out.append(",\n".join(f"({s}, {c}, {q(t)}, {d}, {expr(m)}, 'manual')" for s, c, t, d, m in acts[i:i + 250]) + ";")
    out.append("")
    out.append("INSERT INTO assessments (student_id, course_id, score, assessment_type, title, due_at, submitted_at, assessed_at) VALUES")
    out.append(",\n".join(f"({s}, {c}, {sc}, {q(t)}, {q(ti)}, {du}, {su}, {a})" for s, c, sc, t, ti, du, su, a in asm) + ";\n")
    out.append("-- Predictions and alerts are NOT seeded: generate them in the app (Predictions > Predict whole course; Alerts > Generate).")
    (ROOT / "seed.sql").write_text("\n".join(out) + "\n", encoding="utf-8")

    # sample CSVs for the import feature (valid rows; dates a few days ago, minutes chosen to avoid seed collisions)
    base = datetime.now().replace(second=0, microsecond=0)
    rows = []
    for k, (sid_idx, cid) in enumerate([(0, 1), (1, 2), (2, 3), (4, 1), (6, 3), (8, 1)]):
        pass
    pair_lookup = {(s, c) for _, c, s in enroll}
    chosen = [(s, c) for (s, c) in sorted(pair_lookup)][:6]
    emails = {u[0]: u[2] for u in users}
    cname = {i + 1: n for i, (n, _, _) in enumerate(COURSES)}
    kinds = [("video", 25), ("study_session", 45), ("material", 10), ("login", 0)]
    r2 = np.random.default_rng(3)
    for s, c in chosen:
        for j, (t, d) in enumerate(kinds):
            when = base - timedelta(days=int(r2.integers(1, 4)), hours=j + 1, minutes=7 + j)
            rows.append([emails[s], cname[c], t, d + int(r2.integers(0, 15)) if d else 0, when.strftime("%Y-%m-%d %H:%M")])
    arows = [["student_email", "course_name", "activity_type", "duration", "activity_time"]] + rows
    brows = [["student_email", "course_name", "assessment_type", "title", "score", "due_at", "submitted_at", "assessed_at"]]
    for s, c in chosen:
        due = base - timedelta(days=5)
        brows.append([emails[s], cname[c], "quiz", "Imported Quiz A", int(r2.integers(40, 95)), "", "", (base - timedelta(days=4)).strftime("%Y-%m-%d %H:%M")])
        brows.append([emails[s], cname[c], "assignment", "Imported Assignment A", int(r2.integers(45, 98)), due.strftime("%Y-%m-%d %H:%M"),
                      (due + timedelta(hours=int(r2.integers(-5, 40)))).strftime("%Y-%m-%d %H:%M"), (base - timedelta(days=3)).strftime("%Y-%m-%d %H:%M")])
    for folder in (ROOT, ROOT.parent / "frontend" / "static" / "samples"):
        folder.mkdir(parents=True, exist_ok=True)
        for name, data in (("sample_activities.csv", arows), ("sample_assessments.csv", brows)):
            with open(folder / name, "w", newline="", encoding="utf-8") as fh:
                csv.writer(fh).writerows(data)
    print(f"seed.sql: {len(users)} users, {len(COURSES)} courses, {len(enroll)} enrolments, {len(acts)} activities, {len(asm)} assessments")


if __name__ == "__main__":
    main()
